# ══════════════════════════════════════════════════════════════════════
# 冒号是【分隔符】，几个槽位就需要几-1 个冒号
#
#     s[ 2 : 6 : 2 ]
#        ↑ ↑ ↑ ↑ ↑
#        │ │ │ │ └─ 步长（step）：隔几个取一个
#        │ │ │ └─── 第二个冒号：分隔「终点」和「步长」
#        │ │ └───── 终点（end）：取到这里之前（不含）
#        │ └─────── 第一个冒号：分隔「起点」和「终点」
#        └───────── 起点（start）：从这里开始（含）
#
# 所以：
#     s[2]        0 个冒号 → 不是切片，就是取第 2 个字符，返回单个字符
#     s[2:6]      1 个冒号 → 起点:终点
#     s[2:6:2]    2 个冒号 → 起点:终点:步长
#
# 【省略的是「值」，不是「冒号」】—— 冒号是位置标记，少一个 Python 就不知道
# 那个数字该算哪一项：
#
#     s[:1]     1 个冒号 → 那个 1 被当作【终点】  → 'A'（前 1 个）
#     s[::1]    2 个冒号 → 那个 1 被当作【步长】  → 整个字符串
#
# 同一个数字 1，冒号数不同，含义完全不同。
# 这和函数传参一个道理：位置决定含义，所以占位的冒号不能省。
# ══════════════════════════════════════════════════════════════════════

s = "北京今天天气晴朗，气温 25°C，适合外出活动。"
print(f"  原文({len(s)} 字): {s}")

# ── 1 个冒号：起点:终点 ────────────────────────────────────────────────
print(f"  s[:6]    = {s[:6]!r}       前 6 个（起点省略=从头）")
print(f"  s[6:12]  = {s[6:12]!r}     第 6~11 个（含 6，不含 12）")
print(f"  s[-6:]      = {s[-6:]!r}   最后 6 个（起点 -6 从末尾数，终点省略=一直到尾）")
print(f"  s[-6:-9:-1] = {s[-6:-9:-1]!r}         从 -6 向左取到 -9 前（步长 -1，结果是反序的）")
print(f"  s[-6:-3]    = {s[-6:-3]!r}         从 -6 向右取到 -3 前（不含 -3，共 3 个）")

# ── 2 个冒号：起点:终点:步长 ───────────────────────────────────────────
print(f"  s[::2]   = {s[::2]!r}      每隔一个取（第三个数是步长）")

# s[::-1] 步长为负 = 倒着走，是「倒序」的惯用写法。
# 后面那个 [:12] 是【第二对方括号】—— 一个独立的切片，作用在倒序的结果上。
# 两对方括号 = 两步操作，从左到右执行：
#     ① s[::-1]  倒序，得到一个 24 字的新字符串
#     ② [:12]    取它的前 12 个
# 末尾那个 … 是手写的普通文字，提示「被截断了，后面还有」，不是代码产生的。
print(f"  s[::-1]  = {s[::-1][:12]!r}…  倒序")

# ⚠ 别把 [:12] 和 [::12] 搞混 —— 冒号数决定那个 12 是终点还是步长：
rev = s[::-1]
print(f"  rev[:12]  = {rev[:12]!r}   ← 1 个冒号：取前 12 个")
print(f"  rev[::12] = {rev[::12]!r}                    ← 2 个冒号：隔 12 个取一个")

# 关键：切片超出长度不会报错，给多少算多少
print(f"  '短'[:40] = {'短'[:40]!r}   ← 不用先判断长度，直接切就行")

# ── 坑：负步长时，起点和终点的方向会反 ─────────────────────────────────
print()
print("  ⚠ 负步长时起点终点的方向会反：")
t = "abcdef"
print(f"    t = {t!r}")
print(f"    t[1:4]    = {t[1:4]!r}      正常：从第 1 个走到第 3 个")
print(f"    t[1:4:-1] = {t[1:4:-1]!r}         空的！要从 1 倒着走到 4，方向不对")
print(f"    t[4:1:-1] = {t[4:1:-1]!r}      对了：从第 4 个倒着走到第 2 个")
print(f"    t[4:0:-2] = {t[4:0:-2]!r}      对了：从第 4 个倒着走到第 1 个，跳跃步骤为2")
print("    所以倒序基本只用 [::-1] 这种省略起点终点的写法，")
print("    一旦带上起点终点就很容易搞错方向。")
