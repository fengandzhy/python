"""格式说明符：冒号后面那一串不是随手写的，是一门有固定语法的迷你语言。

    python3 strings/strings-demo05.py

拆自 01_strings.py 的第 ④ 节。
"""

#==============================================
print()
print("═" * 62)
print("④ 格式说明符 —— 冒号后面控制对齐和宽度")
print("═" * 62)
# 出处：demos/chapter1/06_memory_scope.py 里的 f"  第{i}轮  {q:<12}{n:<8}"

# ── ④-1 对齐符 + 宽度 ──────────────────────────────────────────────
# f-string 的槽位是 {值:格式说明符}：冒号左边是要打印的东西，右边是怎么排版。
# 文字列左对齐、数字列右对齐，是表格的常规做法 —— 数字右对齐后个位数能对成
# 一列，690 / 803 / 953 的末位上下对齐，一眼能比大小。
print()
print("  ④-1 对齐符和宽度")

rows = [("北京", 25, 690), ("上海", 26, 803), ("广州", 30, 953)]
print(f"  {'城市':<8}{'气温':>6}{'tokens':>10}")
for c, t, tok in rows:
    print(f"  {c:<8}{t:>6}{tok:>10}")
print("    <  左对齐    >  右对齐    ^  居中    数字是宽度")

# 注意上面那张表其实是歪的：<8 数的是「字符个数」，不是终端里的「显示格数」。
# "北京" 是 2 个字符，Python 补 6 个空格；但等宽终端里一个汉字占 2 格，于是
# 这一列实际占了 10 格。纯英文表格没这问题，中英混排要自己按
# unicodedata.east_asian_width 算宽度，或者用 wcwidth 库。
print("    ⚠ 汉字占 2 格但只算 1 个字符，所以「城市」那列看着比 8 宽")

# ── ④-2 宽度是「最小宽度」，不是「固定宽度」──────────────────────
# 超出不会截断、也不会报错，那一行被整体撑宽，后面的列跟着往右挪。
print()
print("  ④-2 内容超长时不截断，只会把表格挤歪")

long_rows = [("北京", 25, 690), ("Amsterdam-Zuid", 26, 803), ("广州", 30, 953)]
for c, t, tok in long_rows:
    print(f"  {c:<8}{t:>6}{tok:>10}")
# repr() 把引号打出来，隐形的空格才看得见 —— 这个工具见 strings-demo06.py。
print(f"    {'Amsterdam-Zuid':<8} 是 14 个字符 → " + repr(f"{'Amsterdam-Zuid':<8}"))
print("    一个空格都没补，因为宽度只保证「不少于」，不保证「不多于」")

# ── ④-3 想砍掉超出部分：加 .精度 ──────────────────────────────────
# 这里的 8.8 不是小数！那个点是分隔符，不是小数点。说明符的结构是：
#     [填充][对齐][正负号][#][0][宽度][分组符][.精度][类型]
#                              ↑              ↑
#                            这里是 8       这里是 8
# 两个 8 是两个互不相干的整数，碰巧一样而已。
print()
print("  ④-3 .精度 —— 对字符串来说是「最多取几个字符」")

for c, t, tok in long_rows:
    print(f"  {c:<8.8}{t:>6}{tok:>10}")
print("    列宽稳住了，代价是名字被砍")

# 宽度和精度完全可以不同。顺序固定：先按精度截断，再按宽度补齐。
s = "Amsterdam-Zuid"
for spec in ("<8.8", "<12.3", "<3.10", "<20.5"):
    print(f"    {spec:<8} → {('{:' + spec + '}').format(s)!r}")
print("    <12.3 先砍到 3 个字符，再补齐到 12 格")

# 想让读者知道被截过，就手工加省略号：
name = s if len(s) <= 8 else s[:7] + "…"
print(f"    带省略号: {name:<8}|")

# 宽度不能是小数 —— 终端按字符格排，没有半格，写了直接报错。
try:
    "{:<8.5.5}".format(s)
except ValueError as e:
    print(f"    {'<8.5.5':<8} → ValueError: {e}")
